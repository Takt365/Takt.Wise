/**
 * Takt全局物料实体字段 i18n：index / general-material-form 统一入口
 */
export function useGeneralMaterialI18n() {
  const ef = useEntityFieldI18n(GENERALMATERIAL_ENTITY_SLUG)

  function ph(field: GeneralMaterialField): string {
    return ef.placeholder(field, GENERALMATERIAL_PLACEHOLDER[field])
  }

  function queryPh(field: GeneralMaterialQueryField, kind: EntityFieldPlaceholderKind): string {
    return ef.queryPlaceholder(field, kind)
  }

  return {
    t: ef.t,
    label: ef.label,
    queryLabel: ef.queryLabel,
    queryPh,
    self: ef.self,
    ph,
  }
}
